#include "iostream"

int main()
{
    // O loop For é uma estrutura de repetição pré-definidos, efetuando as instruções e incrementando a variável contadora automaticamente. O for pode ser definido como "Para algo, faça isso".

    // Exemplo de Utilização:
    for (int i = 0; i < 10; i++)
    {
        std::cout << "Numero: " << i << '\n';
    }

    // No for, da para declarar e incrementar a variável dentro do método

    
    return 0;
}