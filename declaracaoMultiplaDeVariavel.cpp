#include "iostream"

int main()
{
    // A declaração múltipla de variável é o ato de declarar diversas variáveis ao mesmo tempo, facilitando a leitura e diminuindo a quantidade de linhas. Exemplo:

    int a, b, c;

    // A declaração pode ser feito incrementando valores neles. Exemplo:
    int d = 1, e = 2, f = 3;

    // Outro método de declarar as varíaveis seria orientando os tipos. Exemplo:

    int g = 9; float h = 8.8; bool i = true; // Nestes casos, utiliza-se o ponto e vírgula.

    std::cout << g << '\n' << h << '\n' << i << '\n'; // Demonstração

    return 0;
}